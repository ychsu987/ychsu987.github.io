#!/usr/bin/env python3
"""Build RStudio packs from live-html tutorial wrappers in any course folder.

Website tutorials stay live-html + {webr} with ::: {.hide} solutions.
This script writes standalone .qmd files that use {r} instead of {webr}:

  python scripts/pack_tutorials.py
  python scripts/pack_tutorials.py courses/2026/BBMS1021
  python scripts/pack_tutorials.py courses/2026/BBMS1021/tutorial_1.qmd
  python scripts/pack_tutorials.py --course BBMS1021
  python scripts/pack_tutorials.py --course 2026/BBMS1021

--mode worksheet  drop hide blocks (student RStudio worksheet)
--mode notes      unwrap hide blocks so answers are visible (teacher notes)
--mode both       write both (default)

Outputs go under _student/ (gitignored, not published).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import flatten_qmd as fq  # noqa: E402

GENERATED_MARK = "Generated by scripts/pack_tutorials.py"
LEGACY_GENERATED_MARK = "Generated by scripts/pack_bbms1021_tutorials.py"
COURSES_DIR = "courses"
SKIP_STEM_SUFFIXES = (
    "-full",
    "-worksheet",
    "-notes",
    "-sketch",
    "-blank",
)
# tutorial_1.qmd, Tutorial-2.qmd, week1_tutorial.qmd, …
TUTORIAL_NAME_RE = re.compile(r"(^|[-_])tutorial", re.I)
FENCE_OPEN_RE = re.compile(r"^`{3,}")
DIV_OPEN_RE = re.compile(r"^(?P<colons>:{3,})\s*\{(?P<attrs>[^}]*)\}\s*$")
DIV_CLOSE_RE = re.compile(r"^(?P<colons>:{3,})\s*$")
WEBR_FENCE_RE = re.compile(r"^```\{webr(?P<opts>[^}]*)\}", re.M)
YAML_SPLIT_RE = re.compile(r"^---\s*$", re.M)


def split_yaml(text: str) -> tuple[str | None, str]:
    if not text.startswith("---"):
        return None, text
    parts = YAML_SPLIT_RE.split(text, maxsplit=2)
    if len(parts) >= 3:
        return parts[1], parts[2].lstrip("\n")
    return None, text


def pack_yaml(original_yaml: str | None, title_suffix: str | None) -> str:
    lines = [
        'title: "Tutorial"',
        "format:",
        "  html:",
        "    toc: true",
        "    toc-depth: 3",
        "    toc-location: left",
        "    self-contained: true",
        "engine: knitr",
        "eval: false",
        "lightbox: true",
        'author: "Yu Cheng Hsu"',
    ]
    title = "Tutorial"
    author = None
    date = None
    if original_yaml:
        for raw in original_yaml.splitlines():
            stripped = raw.strip()
            if stripped.startswith("title:"):
                title = stripped.split(":", 1)[1].strip().strip('"').strip("'")
            elif stripped.startswith("author:"):
                author = stripped.split(":", 1)[1].strip()
            elif stripped.startswith("date:"):
                date = stripped.split(":", 1)[1].strip()
    if title_suffix:
        title = f"{title} — {title_suffix}"
    lines[0] = f'title: "{title}"'
    if author:
        lines = [ln for ln in lines if not ln.startswith("author:")]
        lines.append(f"author: {author}")
    if date:
        lines.append(f"date: {date}")
    return "---\n" + "\n".join(lines) + "\n---\n"


def webr_to_r(text: str) -> str:
    return WEBR_FENCE_RE.sub(r"```{r\g<opts>}", text)


def is_hide_attrs(attrs: str) -> bool:
    token = attrs.strip()
    if token == ".hide" or token.startswith(".hide ") or token.startswith(".hide."):
        return True
    return bool(re.search(r"(^|[\s.])hide($|[\s.])", token))


def transform_hide_blocks(text: str, mode: str) -> str:
    """mode=worksheet removes hide blocks; mode=notes unwraps them."""
    out: list[str] = []
    hide_depth = 0
    div_stack: list[tuple[int, bool]] = []
    in_fence = False
    for line in text.splitlines(keepends=True):
        core = line.split("\n", 1)[0]
        stripped = core.strip()
        if FENCE_OPEN_RE.match(stripped):
            in_fence = not in_fence
            if hide_depth == 0 or mode == "notes":
                out.append(line)
            continue
        if in_fence:
            if hide_depth == 0 or mode == "notes":
                out.append(line)
            continue
        open_m = DIV_OPEN_RE.match(stripped)
        if open_m:
            n = len(open_m.group("colons"))
            hide = is_hide_attrs(open_m.group("attrs"))
            div_stack.append((n, hide))
            if hide:
                hide_depth += 1
                if mode == "notes":
                    continue
            if hide_depth == 0 or mode == "notes":
                out.append(line)
            continue
        close_m = DIV_CLOSE_RE.match(stripped)
        if close_m and div_stack:
            n = len(close_m.group("colons"))
            # close the nearest matching colon count, else the last open
            idx = next(
                (i for i in range(len(div_stack) - 1, -1, -1) if div_stack[i][0] == n),
                len(div_stack) - 1,
            )
            _n, was_hide = div_stack.pop(idx)
            if was_hide:
                hide_depth = max(0, hide_depth - 1)
                if mode == "notes":
                    continue
            if hide_depth == 0 or mode == "notes":
                out.append(line)
            continue
        if hide_depth == 0 or mode == "notes":
            out.append(line)
    return "".join(out)


def is_pack_generated(path: Path) -> bool:
    if not path.is_file():
        return False
    head = path.read_text(encoding="utf-8")[:2000]
    return GENERATED_MARK in head or LEGACY_GENERATED_MARK in head


def write_dest(dest: Path, text: str, root: Path, force: bool) -> bool:
    if dest.exists() and not is_pack_generated(dest) and not force:
        print(
            f"refuse to overwrite source file: {fq.rel_to_root(dest, root)}\n"
            f"  re-run with --out-dir  or  --force",
            file=sys.stderr,
        )
        return False
    dest.write_text(text, encoding="utf-8")
    print(f"wrote {fq.rel_to_root(dest, root)}")
    return True


def insert_comment(yaml_doc: str, body: str, source: Path, kind: str) -> str:
    comment = (
        f"<!-- {GENERATED_MARK} from {source.as_posix()} ({kind}). "
        "Do not edit by hand. -->\n"
    )
    return yaml_doc + "\n" + comment + "\n" + body.lstrip("\n")


def stem_is_skipped(stem: str) -> bool:
    lower = stem.lower()
    return any(lower.endswith(suffix) for suffix in SKIP_STEM_SUFFIXES)


def is_tutorial_filename(path: Path) -> bool:
    if path.suffix.lower() != ".qmd":
        return False
    if stem_is_skipped(path.stem):
        return False
    return bool(TUTORIAL_NAME_RE.search(path.stem))


def looks_like_tutorial_wrapper(path: Path) -> bool:
    """True for website tutorial skins (includes, webr, or .hide solutions)."""
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return False
    head = text[:2000]
    if GENERATED_MARK in head or LEGACY_GENERATED_MARK in head:
        return False
    if fq.GENERATED_MARK in head:
        return False
    sample = text[:12000]
    if "{webr" in sample:
        return True
    if "modules/tutorials/" in sample:
        return True
    if re.search(r":::\s*\{\s*\.hide", sample):
        return True
    if re.search(r"format:\s*\n\s*live-html:", sample):
        return True
    return False


def collect_from_dir(directory: Path) -> list[Path]:
    found: list[Path] = []
    for path in sorted(directory.rglob("*.qmd")):
        if not is_tutorial_filename(path):
            continue
        if looks_like_tutorial_wrapper(path):
            found.append(path.resolve())
    return found


def resolve_course_roots(root: Path, course: str) -> list[Path]:
    """Map --course CODE or YEAR/CODE to courses/... directories."""
    course = course.strip().strip("/")
    courses = root / COURSES_DIR
    if not courses.is_dir():
        return []
    parts = Path(course).parts
    if len(parts) >= 2 and (courses / parts[0] / parts[1]).is_dir():
        return [(courses / parts[0] / parts[1]).resolve()]
    matches = sorted(
        p.resolve()
        for p in courses.glob(f"*/{course}")
        if p.is_dir()
    )
    return matches


def resolve_sources(
    root: Path,
    raw_sources: list[Path],
    course: str | None,
) -> list[Path]:
    """Resolve files/directories/--course into tutorial wrapper paths."""
    paths: list[Path] = []
    seen: set[Path] = set()

    def add(path: Path) -> None:
        path = path.resolve()
        if path not in seen:
            seen.add(path)
            paths.append(path)

    if course:
        roots = resolve_course_roots(root, course)
        if not roots:
            raise FileNotFoundError(f"course not found under {COURSES_DIR}/: {course}")
        for course_root in roots:
            for found in collect_from_dir(course_root):
                add(found)

    if not raw_sources and not course:
        courses = root / COURSES_DIR
        if courses.is_dir():
            for found in collect_from_dir(courses):
                add(found)
        return paths

    for src in raw_sources:
        path = src if src.is_absolute() else (Path.cwd() / src)
        if path.is_dir():
            found = collect_from_dir(path)
            if not found:
                raise FileNotFoundError(
                    f"no packable tutorial .qmd files under: {src}"
                )
            for item in found:
                add(item)
        elif path.is_file():
            add(path)
        else:
            raise FileNotFoundError(f"not found: {src}")
    return paths


def process_file(
    source: Path,
    root: Path,
    mode: str,
    dest_dir: Path,
    force: bool,
    site: str,
) -> list[Path]:
    original = source.read_text(encoding="utf-8")
    yaml_src, _ = split_yaml(original)
    flat = fq.expand_includes(original, source, root)
    flat = fq.rewrite_student_urls(flat, source, root, site)
    _y, body = split_yaml(flat)
    body = webr_to_r(body)
    written: list[Path] = []
    jobs: list[tuple[str, str, str]] = []
    if mode in ("worksheet", "both"):
        jobs.append(("worksheet", "worksheet", "student worksheet"))
    if mode in ("notes", "both"):
        jobs.append(("notes", "notes", "teacher notes"))
    rel = fq.rel_to_root(source, root)
    for suffix, hide_mode, title_suffix in jobs:
        dest = dest_dir / f"{source.stem}-{suffix}.qmd"
        transformed = transform_hide_blocks(body, hide_mode)
        yaml_doc = pack_yaml(yaml_src, title_suffix)
        text = insert_comment(yaml_doc, transformed, rel, suffix)
        if write_dest(dest, text, root, force):
            written.append(dest)
    return written


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Build student worksheets and teacher notes (.qmd, {r} chunks) "
            "from tutorial wrappers in any courses/{YEAR}/{CODE}/ folder."
        )
    )
    parser.add_argument(
        "source",
        nargs="*",
        type=Path,
        help=(
            "Tutorial .qmd file(s) and/or course directories "
            "(default: discover tutorials under courses/)"
        ),
    )
    parser.add_argument(
        "--course",
        type=str,
        default=None,
        help="Limit discovery to a course code (BBMS1021) or YEAR/CODE (2026/BBMS1021)",
    )
    parser.add_argument(
        "--mode",
        choices=["worksheet", "notes", "both"],
        default="both",
        help="worksheet = drop solutions; notes = show solutions; both = write both",
    )
    parser.add_argument(
        "--site",
        default=fq.DEFAULT_SITE,
        help=f"Public site origin for /assets and img/ URLs (default: {fq.DEFAULT_SITE})",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=None,
        help="Output directory (default: _student/<path-of-tutorial>/)",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite an existing file even if it is not a generated copy",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    root = fq.repo_root()
    try:
        sources = resolve_sources(root, list(args.source), args.course)
    except FileNotFoundError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    if not sources:
        print(
            "no packable tutorial wrappers found "
            "(pass a path, directory, or --course)",
            file=sys.stderr,
        )
        return 1
    written = 0
    for path in sources:
        rel = fq.rel_to_root(path, root)
        if args.out_dir is None:
            dest_dir = (root / "_student" / rel.parent).resolve()
        elif args.out_dir.is_absolute():
            dest_dir = args.out_dir.resolve()
        else:
            dest_dir = (path.parent / args.out_dir).resolve()
        dest_dir.mkdir(parents=True, exist_ok=True)
        written += len(
            process_file(path, root, args.mode, dest_dir, args.force, args.site)
        )
    if written == 0:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
